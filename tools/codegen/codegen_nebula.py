# (the heart of the operator). For `build_temporal_point` operators
# we emit a per-event temporal-point build + MEOS call, mirroring
# TemporalEDWithinGeometry; for non-temporal-point operators (future
# templates) the body shape differs and a separate template branch
# would be added here.
