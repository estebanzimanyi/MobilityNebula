def cpp_logical_type(arg):
    """C++ constructor-arg type for a LogicalFunction parameter."""
    return "LogicalFunction"


def cpp_physical_type(arg):
    """C++ constructor-arg type for a PhysicalFunction parameter."""
    return "PhysicalFunction"


def build_ctor_args(args, type_fn):
    return ",\n                                          ".join(
        f"{type_fn(a)} {a['name']}" for a in args
    )


def build_pushes_logical(args):
    return "\n".join(f"    parameters.push_back(std::move({a['name']}));" for a in args)


def build_pushes_physical(args):
    return "\n".join(
        f"    parameterFunctions.push_back(std::move({a['name']}Function));" for a in args
    )


def build_registrar_pushes_logical(args, nebula_name):
    pushes = []
    for i, _ in enumerate(args):
        pushes.append(f"    auto arg{i} = std::move(arguments.children[{i}]);")
    pushes.append(
        f"    return {nebula_name}LogicalFunction(" + ", ".join(f"std::move(arg{i})" for i in range(len(args))) + ");"
    )
    return "\n".join(pushes)


def build_registrar_pushes_physical(args, nebula_name):
    pushes = []
    for i, _ in enumerate(args):
        # PhysicalFunctionRegistryArguments uses `childFunctions`, not `children`
        # (LogicalFunctionRegistryArguments uses `children` — see registry headers).
        pushes.append(f"    auto arg{i} = std::move(arguments.childFunctions[{i}]);")
    pushes.append(
        f"    return {nebula_name}PhysicalFunction(" + ", ".join(f"std::move(arg{i})" for i in range(len(args))) + ");"
    )
    return "\n".join(pushes)


def emit_operator(op, output_root: Path):
    nebula_name = op["nebula_name"]
    n_args = len(op["args"])

    # Logical .hpp constructor args (LogicalFunction type each)
    ctor_logical_args = build_ctor_args(op["args"], cpp_logical_type)
    # Physical .hpp / .cpp constructor args use 'XxxFunction' naming convention
    physical_args = [{"name": a["name"] + "Function"} for a in op["args"]]
    ctor_physical_args = ",\n                                                          ".join(
        f"PhysicalFunction {a['name']}" for a in physical_args
    )

    ctor_logical_pushes = build_pushes_logical(op["args"])
    ctor_physical_pushes = build_pushes_physical(op["args"])
    registrar_l = build_registrar_pushes_logical(op["args"], nebula_name)
    registrar_p = build_registrar_pushes_physical(op["args"], nebula_name)

    common = {
        "nebula_name": nebula_name,
        "comment_one_liner": op["comment_one_liner"],
        "meos_call": op["meos_call"],
        "n_args": n_args,
        "nautilus_return": op["nautilus_return"],
        "return_type": op["return_type"],
        "ctor_logical_args": ctor_logical_args,
        "ctor_physical_args": ctor_physical_args,
        "ctor_logical_pushes": ctor_logical_pushes,
        "ctor_physical_pushes": ctor_physical_pushes,
        "registrar_pushes": registrar_l,
    }

    logical_hpp_path = output_root / "nes-logical-operators/include/Functions/Meos" / f"{nebula_name}LogicalFunction.hpp"
    logical_cpp_path = output_root / "nes-logical-operators/src/Functions/Meos" / f"{nebula_name}LogicalFunction.cpp"
    physical_hpp_path = output_root / "nes-physical-operators/include/Functions/Meos" / f"{nebula_name}PhysicalFunction.hpp"
    physical_cpp_path = output_root / "nes-physical-operators/src/Functions/Meos" / f"{nebula_name}PhysicalFunction.cpp"

    for p in (logical_hpp_path, logical_cpp_path, physical_hpp_path, physical_cpp_path):
        p.parent.mkdir(parents=True, exist_ok=True)

    logical_hpp_path.write_text(LOGICAL_HPP_TEMPLATE.format(**common))
    logical_cpp_path.write_text(LOGICAL_CPP_TEMPLATE.format(**common))
    physical_hpp_path.write_text(PHYSICAL_HPP_TEMPLATE.format(**common))

    physical_common = dict(common)
    physical_common["registrar_pushes"] = registrar_p
    if op.get("build_temporal_point"):
        physical_cpp_path.write_text(PHYSICAL_CPP_TEMPLATE_TEMPORAL_POINT.format(**physical_common))
    else:
        sys.stderr.write(
            f"  ! {nebula_name}: physical-cpp template for non-temporal-point ops is not yet implemented; "
            f"skipping .cpp — the .hpp + logical files are still emitted, but the .cpp must be hand-written.\n"
        )

    sys.stderr.write(f"  ✓ {nebula_name}: emitted 4 files ({logical_hpp_path.relative_to(output_root)} + siblings)\n")

    # Parser dispatch snippet (stderr — manual paste)
    sys.stderr.write(
        f"\n----- PASTE INTO nes-sql-parser/AntlrSQL.g4 (lexer tokens) -----\n"
        f"{op['sql_token']}: '{op['sql_token']}' | '{op['sql_token'].lower()}';\n"
    )
    sys.stderr.write(
        f"----- PASTE INTO nes-sql-parser/src/AntlrSQLQueryPlanCreator.cpp -----\n"
        f"        case AntlrSQLLexer::{op['sql_token']}:\n"
        f"            // Generated by tools/codegen/codegen_nebula.py. {op['comment_one_liner']}\n"
        f"            // 4-arg shape: lon, lat, timestamp, geometry — mirrors TemporalEDWithinGeometry.\n"
        f"            {{\n"
        f"                // Arg-extraction + construct{n_args}-children pattern mirrors the existing\n"
        f"                // TEMPORAL_EDWITHIN_GEOMETRY block in this file. Adopt the same\n"
        f"                // constantBuilder / functionBuilder pop + tryGet<FieldAccessLogicalFunction>\n"
        f"                // gating.\n"
        f"            }}\n"
        f"            break;\n"
        f"----- end snippet -----\n\n"
    )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", required=True, help="Path to JSON descriptor file")
    parser.add_argument("--output-root", required=True, help="MobilityNebula repo root")
    args = parser.parse_args()

    with open(args.input) as f:
        config = json.load(f)

    output_root = Path(args.output_root).resolve()
    if not (output_root / "nes-logical-operators").exists():
        sys.exit(f"ERROR: {output_root} does not look like a MobilityNebula root (no nes-logical-operators/)")

    operators = config["operators"]
    sys.stderr.write(f"Emitting {len(operators)} operator(s):\n\n")
    for op in operators:
        emit_operator(op, output_root)

    sys.stderr.write(
        f"\nDone. {len(operators) * 4} files emitted (or 3 + .cpp-skipped for non-temporal-point ops).\n"
        f"Manual steps after running this script:\n"
        f"  1. Paste the AntlrSQL.g4 lexer-token snippets (above) into the .g4 file\n"
        f"  2. Paste the AntlrSQLQueryPlanCreator.cpp dispatch snippets into the parser\n"
        f"  3. Add the new .cpp files to nes-logical-operators/src/Functions/Meos/CMakeLists.txt\n"
        f"     and nes-physical-operators/src/Functions/Meos/CMakeLists.txt\n"
        f"  4. Run `cmake --build` to compile-verify; expect to iterate on the templates\n"
        f"     for any first-batch compile errors\n"
    )


if __name__ == "__main__":
    main()
