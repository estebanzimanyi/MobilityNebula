#!/usr/bin/env python3
"""MobilityNebula MEOS-operator generator.

Given a JSON descriptor list of MEOS scalar functions to wrap as
NebulaStream operators, emits the 4 pipeline-layer C++ files per
function (logical .hpp/.cpp + physical .hpp/.cpp) following the
established style of the existing hand-written operators (e.g.
TemporalEDWithinGeometryLogicalFunction), AND auto-injects:

- per-op CMakeLists.txt entries in nes-{logical,physical}-operators/
  src/Functions/Meos/
- AntlrSQL.g4 lexer-token + functionName-alternation entries
- AntlrSQLQueryPlanCreator.cpp #include + dispatch-case block

Injection is idempotent — markers like
`/* BEGIN CODEGEN PARSER GLUE: <token> */ … /* END CODEGEN PARSER GLUE */`
gate each per-op block, and the script skips on re-run when the marker
is already present.

Usage:
    python3 codegen_nebula.py --input codegen_input.example.json \\
                              --output-root /path/to/MobilityNebula \\
                              [--no-parser-glue]    # skip .g4 + parser .cpp
                              [--no-cmake-entries]  # skip CMakeLists.txt
"""
