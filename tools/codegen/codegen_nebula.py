#!/usr/bin/env python3
"""MobilityNebula MEOS-operator generator.

Given a JSON descriptor list of MEOS scalar functions to wrap as
NebulaStream operators, emits the 4 pipeline-layer C++ files per
function (logical .hpp/.cpp + physical .hpp/.cpp) following the
established style of the existing hand-written operators (e.g.
TemporalEDWithinGeometryLogicalFunction).

Also emits to stderr:
- The parser-dispatch snippet to paste into
  nes-sql-parser/src/AntlrSQLQueryPlanCreator.cpp
- The grammar snippet to paste into nes-sql-parser/AntlrSQL.g4
- The CMakeLists snippets to paste into the respective
  CMakeLists.txt files

The CMakeLists / parser / grammar are NOT auto-modified — manual paste
keeps the generator idempotent and prevents silent corruption on
regeneration.

Usage:
    python3 codegen_nebula.py --input codegen_input.example.json \\
                              --output-root /path/to/MobilityNebula
"""
